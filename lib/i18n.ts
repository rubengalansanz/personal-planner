export const translations: Record<Language, Translations> = {
  es,
  en,
  de,
  fr,
  it,
  pt,
};

export type Translator = (
  path: string,
  params?: Record<string, string | number>,
) => string;

export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && value in translations;
}

function lookup(dictionary: unknown, path: string): string | undefined {
  let current: unknown = dictionary;
  for (const key of path.split(".")) {
    if (current && typeof current === "object" && key in (current as object)) {
      current = (current as Record<string, unknown>)[key];
    } else {
      return undefined;
    }
  }
  return typeof current === "string" ? current : undefined;
}

function interpolate(
  value: string,
  params?: Record<string, string | number>,
): string {
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in params ? String(params[key]) : match,
  );
}

export function translate(
  language: Language,
  path: string,
  params?: Record<string, string | number>,
): string {
  const value =
    lookup(translations[language] ?? translations[DEFAULT_LANGUAGE], path) ??
    lookup(translations[DEFAULT_LANGUAGE], path) ??
    path;
  return interpolate(value, params);
}

export function translatorFor(language: Language): Translator {
  return (path, params) => translate(language, path, params);
}
